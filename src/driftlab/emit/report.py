"""Human-readable cycle report (markdown). Deterministic body; the optional
LLM narrative is clearly fenced as advisory and never carries findings."""

from __future__ import annotations

from typing import Any

from driftlab.baseline.model import BaselinePolicy
from driftlab.domain.models import CycleResult, Severity
from driftlab.llm import narrate

_SEV_ICONS = {"critical": "[CRITICAL]", "high": "[HIGH]", "medium": "[MEDIUM]", "low": "[LOW]", "info": "[INFO]"}


def build_markdown_report(
    cycle: CycleResult,
    policy: BaselinePolicy,
    *,
    llm: Any | None = None,
) -> str:
    lines: list[str] = []
    add = lines.append

    add(f"# DriftLab cycle report — {cycle.agent_id}")
    add("")
    add(f"- **Cycle**: `{cycle.cycle_id}`")
    add(f"- **Baseline**: {policy.title or cycle.baseline_id} v{policy.version} ({policy.status}) — `{cycle.baseline_hash[:12]}`")
    add(f"- **Trace**: {cycle.runs_observed} runs / {cycle.events_observed} decision events — `{cycle.trace_hash[:12]}`")
    add(f"- **Window**: {cycle.started_at or 'n/a'} -> {cycle.finished_at or 'n/a'}")
    add("")
    add(f"## Compliance score: {cycle.compliance_score} / 100")
    add("")
    if cycle.severity_counts:
        add("| Severity | Count |")
        add("|---|---|")
        for severity in Severity:
            count = cycle.severity_counts.get(severity.value, 0)
            if count:
                add(f"| {severity.value} | {count} |")
        add("")
    else:
        add("No behavioral drift observed. All certified controls satisfied this cycle.")
        add("")

    if cycle.anomalies:
        add("## Anomalies")
        add("")
        for anomaly in sorted(cycle.anomalies, key=lambda a: a.fingerprint):
            icon = _SEV_ICONS.get(anomaly.severity.value, "[?]")
            add(f"### {icon} {anomaly.title}")
            add("")
            add(f"- **Control**: {(anomaly.control_id or 'n/a').upper()} | **Kind**: {anomaly.kind.value} | **Fingerprint**: `{anomaly.fingerprint}`")
            add(f"- **Waiver**: {anomaly.waiver_status}")
            add(f"- {anomaly.description}")
            if anomaly.measurement:
                add(f"- **Measurement**: `{anomaly.measurement}`")
            if anomaly.evidence.run_ids:
                add(f"- **Evidence runs**: {', '.join(anomaly.evidence.run_ids[:12])}")
            reaches = [p for p in anomaly.impacted_paths if p.reaches_critical_sink]
            if reaches:
                add(f"- **Reaches critical sink** via: {' -> '.join(reaches[0].node_path) or 'direct'}")
            add("")

    if cycle.experiments:
        add("## Micro-experiments (drift proof)")
        add("")
        for experiment in sorted(cycle.experiments, key=lambda e: e.hypothesis.anomaly_fingerprint):
            verdict = experiment.verdict.value.upper()
            add(f"### {verdict} — {experiment.hypothesis.kind.value}")
            add("")
            add(f"- **Hypothesis**: {experiment.hypothesis.statement}")
            add(f"- **Expected under baseline**: {experiment.hypothesis.expected_under_baseline}")
            add(f"- **Validity**: {experiment.validity_score} | **Iterations**: {experiment.iterations} | **Probes**: {len(experiment.probes)}")
            for probe in experiment.probes:
                add(
                    f"  - probe `{probe.probe_id}`: {probe.violations}/{probe.samples} violations "
                    f"(rate {probe.violation_rate})"
                )
            if experiment.narrative:
                add(f"- **Analyst note (LLM, advisory)**: {experiment.narrative}")
            add("")

    narrative = _cycle_narrative(cycle, llm)
    if narrative:
        add("## Narrative (LLM, advisory — not part of the compliance record)")
        add("")
        add(narrative)
        add("")

    add("---")
    add("*Generated by DriftLab. Findings and verdicts are produced by the deterministic*")
    add("*compliance path; prose marked advisory comes from a local LLM and carries no authority.*")
    add("")
    return "\n".join(lines)


def _cycle_narrative(cycle: CycleResult, llm: Any | None) -> str | None:
    if llm is None or not cycle.anomalies:
        return None
    confirmed = [e for e in cycle.experiments if e.verdict.value == "confirmed"]
    prompt = (
        "Write a 3-5 sentence executive summary for a compliance officer. Facts (do not "
        f"invent others): agent '{cycle.agent_id}' scored {cycle.compliance_score}/100; "
        f"severity counts {cycle.severity_counts}; anomalies: "
        f"{[a.title for a in cycle.anomalies]}; experimentally confirmed drifts: "
        f"{[e.hypothesis.kind.value for e in confirmed]}. Neutral regulatory tone."
    )
    return narrate(llm, prompt)
