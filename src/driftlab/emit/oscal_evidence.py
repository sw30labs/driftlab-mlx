"""OSCAL evidence emitter — assessment-plan + per-cycle assessment-results.

Follows the OscalAssessmentSink pattern from OSCAL-skills-guardrails, with two
upgrades: (a) a real assessment-plan artifact is generated from the certified
baseline instead of the import-ap→profile shortcut, and (b) CA-7 (continuous
monitoring) anchors the whole family — every cycle is a CA-7 attestation.

All artifact/observation/finding UUIDs are deterministic (uuid5 of cycle +
fingerprint): re-emitting evidence for the same cycle is byte-stable except
for provenance timestamps, which are real assessment times by design.

One deliberate, documented deviation from strict OSCAL: assessment-plan's
``import-ssp`` points at the baseline *profile* (no SSP exists for a single
agent in v1). The remarks field declares this; a full component-definition +
SSP pair is roadmap v2.
"""

from __future__ import annotations

from typing import Any

from driftlab.baseline.model import BaselinePolicy
from driftlab.domain.models import AnomalyRecord, CycleResult, ExperimentRecord
from driftlab.identity import deterministic_uuid

OSCAL_VERSION = "1.1.2"
DL_NS = "https://sw30labs.com/ns/dl"


def _prop(name: str, value: Any) -> dict[str, str]:
    return {"name": name, "value": str(value), "ns": DL_NS}


def _all_controls(policy: BaselinePolicy) -> list[str]:
    return sorted(set(policy.control_map.values()))


def build_assessment_plan(policy: BaselinePolicy, *, timestamp: str) -> dict[str, Any]:
    """Assessment plan derived from the certified baseline: one task per
    behavioral control check, methods TEST, continuous cadence (CA-7)."""
    plan_uuid = deterministic_uuid(f"assessment-plan:{policy.agent_id}:{policy.baseline_hash}")
    tasks = []
    checks = [
        ("tools", "Verify every observed tool call is on the certified allowlist"),
        ("routes", "Verify every observed routing transition is certified"),
        ("hitl", "Verify matching decisions escalate to the certified human gate"),
        ("fallback", "Verify errors are followed by the certified fallback path"),
        ("critical_sink", "Escalate severity for drift on paths reaching critical sinks"),
        ("autonomy", "Verify the full-autonomy fraction stays within the certified budget"),
        ("steps", "Verify certified required steps execute in every run"),
    ]
    for area, description in checks:
        control_id = policy.control_map.get(area)
        if control_id is None:
            continue
        tasks.append(
            {
                "uuid": deterministic_uuid(f"task:{policy.agent_id}:{policy.baseline_hash}:{area}"),
                "type": "action",
                "title": f"Continuously monitor {control_id.upper()} ({area})",
                "description": description,
                "props": [_prop("dl:control", control_id), _prop("dl:method", "behavioral-diff")],
            }
        )
    return {
        "assessment-plan": {
            "uuid": plan_uuid,
            "metadata": {
                "title": f"DriftLab continuous assessment plan — {policy.agent_id}",
                "version": policy.version,
                "oscal-version": OSCAL_VERSION,
                "last-modified": timestamp,
                "props": [
                    _prop("dl:agent-id", policy.agent_id),
                    _prop("dl:baseline-hash", policy.baseline_hash),
                ],
                "remarks": (
                    "Generated by DriftLab from the certified baseline profile. Pragmatic "
                    "deviation: import-ssp references the baseline profile because no SSP "
                    "exists for a single agent in v1 (component-definition + SSP planned). "
                    "Assessment cadence is continuous — this plan implements CA-7 for agent "
                    "behavior."
                ),
            },
            "import-ssp": {"href": policy.source_path or "baseline-profile.json"},
            "reviewed-controls": {
                "control-selections": [
                    {"include-controls": [{"control-id": cid} for cid in _all_controls(policy)]}
                ]
            },
            "tasks": tasks,
        }
    }


def _anomaly_observation(cycle: CycleResult, anomaly: AnomalyRecord) -> dict[str, Any]:
    return {
        "uuid": deterministic_uuid(f"obs:{cycle.cycle_id}:{anomaly.fingerprint}"),
        "title": f"drift: {anomaly.title}",
        "description": anomaly.description,
        "methods": ["TEST"],
        "props": [
            _prop("dl:kind", anomaly.kind.value),
            _prop("dl:severity", anomaly.severity.value),
            _prop("dl:fingerprint", anomaly.fingerprint),
            _prop("dl:control", anomaly.control_id or ""),
            _prop("dl:agent-id", cycle.agent_id),
            _prop("dl:cycle-id", cycle.cycle_id),
            _prop("dl:trace-hash", cycle.trace_hash),
            _prop("dl:baseline-hash", cycle.baseline_hash),
            _prop("dl:waiver-status", anomaly.waiver_status),
        ],
        "subjects": [
            {
                "subject-uuid": deterministic_uuid(f"component:{cycle.agent_id}"),
                "type": "component",
                "title": cycle.agent_id,
            }
        ],
        "relevant-evidence": [
            {
                "description": (
                    f"Evidence events: {', '.join(anomaly.evidence.event_ids[:10]) or 'n/a'}; "
                    f"runs: {', '.join(anomaly.evidence.run_ids[:10]) or 'n/a'}; "
                    f"measurement: {anomaly.measurement}"
                )
            }
        ],
        "collected": cycle.finished_at or cycle.started_at or "",
    }


def _experiment_observation(cycle: CycleResult, experiment: ExperimentRecord) -> dict[str, Any]:
    hyp = experiment.hypothesis
    last = experiment.probes[-1] if experiment.probes else None
    return {
        "uuid": deterministic_uuid(f"obs-exp:{cycle.cycle_id}:{hyp.anomaly_fingerprint}"),
        "title": f"micro-experiment: {experiment.verdict.value.upper()} — {hyp.kind.value}",
        "description": (
            f"Hypothesis: {hyp.statement} Expected under baseline: {hyp.expected_under_baseline} "
            f"Verdict: {experiment.verdict.value} (validity {experiment.validity_score}, "
            f"{experiment.iterations} iteration(s), {len(experiment.probes)} probe(s))."
        ),
        "methods": ["TEST"],
        "props": [
            _prop("dl:verdict", experiment.verdict.value),
            _prop("dl:validity", experiment.validity_score),
            _prop("dl:fingerprint", hyp.anomaly_fingerprint),
            _prop("dl:control", hyp.control_id or ""),
            _prop("dl:probes", len(experiment.probes)),
            _prop("dl:probe-violations", last.violations if last else 0),
            _prop("dl:probe-samples", last.samples if last else 0),
            _prop("dl:sandbox", "replay"),
        ],
        "subjects": [
            {
                "subject-uuid": deterministic_uuid(f"component:{cycle.agent_id}"),
                "type": "component",
                "title": cycle.agent_id,
            }
        ],
        "collected": cycle.finished_at or cycle.started_at or "",
    }


def build_assessment_results(
    cycle: CycleResult,
    policy: BaselinePolicy,
    *,
    plan_href: str = "assessment-plan.json",
) -> dict[str, Any]:
    """One OSCAL assessment-results document per monitor cycle."""
    observations = [_anomaly_observation(cycle, a) for a in sorted(cycle.anomalies, key=lambda a: a.fingerprint)]
    observations += [
        _experiment_observation(cycle, e)
        for e in sorted(cycle.experiments, key=lambda e: e.hypothesis.anomaly_fingerprint)
    ]

    findings: list[dict[str, Any]] = []
    violated_controls: dict[str, list[AnomalyRecord]] = {}
    for anomaly in cycle.anomalies:
        if anomaly.control_id and anomaly.waiver_status == "none":
            violated_controls.setdefault(anomaly.control_id, []).append(anomaly)

    experiment_by_fp = {e.hypothesis.anomaly_fingerprint: e for e in cycle.experiments}

    for control_id in _all_controls(policy):
        anomalies = violated_controls.get(control_id, [])
        state = "not-satisfied" if anomalies else "satisfied"
        related = [
            {"observation-uuid": deterministic_uuid(f"obs:{cycle.cycle_id}:{a.fingerprint}")}
            for a in sorted(anomalies, key=lambda a: a.fingerprint)
        ]
        for a in sorted(anomalies, key=lambda a: a.fingerprint):
            if a.fingerprint in experiment_by_fp:
                related.append(
                    {"observation-uuid": deterministic_uuid(f"obs-exp:{cycle.cycle_id}:{a.fingerprint}")}
                )
        titles = "; ".join(a.title for a in anomalies) if anomalies else "no behavioral drift observed"
        findings.append(
            {
                "uuid": deterministic_uuid(f"finding:{cycle.cycle_id}:{control_id}"),
                "title": f"{control_id.upper()}: {titles}",
                "description": (
                    f"Continuous behavioral assessment of {control_id.upper()} for agent "
                    f"'{cycle.agent_id}' over {cycle.runs_observed} run(s) / "
                    f"{cycle.events_observed} decision event(s)."
                ),
                "target": {
                    "type": "objective-id",
                    "target-id": f"{control_id}_smt",
                    "status": {"state": state},
                },
                **({"related-observations": related} if related else {}),
            }
        )

    return {
        "assessment-results": {
            "uuid": deterministic_uuid(f"assessment-results:{cycle.cycle_id}"),
            "metadata": {
                "title": f"DriftLab monitoring cycle — {cycle.agent_id} — {cycle.cycle_id}",
                "version": "1.0.0",
                "oscal-version": OSCAL_VERSION,
                "last-modified": cycle.finished_at or cycle.started_at or "",
                "props": [
                    _prop("dl:agent-id", cycle.agent_id),
                    _prop("dl:cycle-id", cycle.cycle_id),
                    _prop("dl:compliance-score", cycle.compliance_score),
                ],
                "remarks": (
                    "Machine-generated continuous-monitoring evidence (CA-7). Deterministic "
                    "compliance path: findings derive from behavioral diff against the "
                    "certified baseline; micro-experiment observations carry reproduction "
                    "evidence for suspected drift."
                ),
            },
            "import-ap": {"href": plan_href},
            "results": [
                {
                    "uuid": deterministic_uuid(f"result:{cycle.cycle_id}"),
                    "title": f"Cycle {cycle.cycle_id}",
                    "description": (
                        f"Compliance score {cycle.compliance_score}; severity counts "
                        f"{cycle.severity_counts}; baseline {cycle.baseline_id} "
                        f"({cycle.baseline_hash[:12]}); trace hash {cycle.trace_hash[:12]}."
                    ),
                    "start": cycle.started_at or "",
                    "end": cycle.finished_at or "",
                    "reviewed-controls": {
                        "control-selections": [
                            {"include-controls": [{"control-id": cid} for cid in _all_controls(policy)]}
                        ]
                    },
                    "observations": observations,
                    "findings": findings,
                }
            ],
        }
    }
